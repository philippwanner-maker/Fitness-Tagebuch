const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const mod={exports:{}};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../public/app.js'),'utf8'),{module:mod,crypto:require('node:crypto').webcrypto});
const {pointsFor,overallProgress,muscleActivity,muscleGroup,personalRecords}=mod.exports;
const w=(date,name,weights,reps=8)=>({date,dayId:'active',exercises:[{name,body:false,sets:weights.map(weight=>({weight,reps}))}]});
const ws=[w('2026-10-01','Bankdrücken',[40,60]),w('2026-10-01','bankdrücken',[80]),w('2026-10-02','Bankdrücken',[90]),w('2026-10-01','Rudern',[20]),w('2026-10-03','Rudern',[20])];
assert.equal(pointsFor(ws,'Bankdrücken').length,2);
assert.equal(pointsFor(ws,'Bankdrücken')[0].value,60,'each completed set counts equally across sessions on same day');
const total=overallProgress(ws);
assert.equal(total[0].value,100);assert.equal(total[1].value,125);assert.equal(total[2].value,125,'carry other exercises forward');
assert.equal(overallProgress([w('2026-10-01','Liegestütze',[0])]).length,0,'no division by zero');
assert.equal(pointsFor([w('2026-10-01','Test',[40,'',60]),w('2026-10-01','Test',[900],0)],'Test')[0].value,50,'exclude incomplete sets');
assert.equal(pointsFor([w('2026-10-01','Test',[40],13)],'Test')[0].e1rm,null);
assert.equal(pointsFor([w('2026-10-01','Test',[40],1)],'Test')[0].e1rm,40);
const heat=muscleActivity([...ws,w('2026-09-22','Bankdrücken',[999]),w('2026-10-23','Bankdrücken',[999])],'2026-10-22');
assert.equal(heat.find(x=>x.name==='Brust').sets,4);
assert(heat.find(x=>x.name==='Brust').intensity>0);
assert(heat.find(x=>x.name==='Rücken').intensity>0,'completed sets light up even without strength gains');
assert(heat.find(x=>x.name==='Brust').intensity>heat.find(x=>x.name==='Rücken').intensity,'more sets mean higher intensity');
assert.equal(heat.find(x=>x.name==='Beine').intensity,0);
assert.equal(muscleGroup('Reverse Flys'),'Schultern');assert.equal(muscleGroup('Enges Bankdrücken'),'Arme');
assert.equal(muscleGroup('Meine unbekannte Übung'),null);
const records=personalRecords([w('2026-10-01','Bankdrücken',[60],8),w('2026-10-02','Bankdrücken',[70],5),w('2026-10-03','Rudern',[50],10)]);
const bench=records.find(r=>r.name==='Bankdrücken');
assert.equal(bench.weight.value,70);assert.equal(bench.weight.date,'2026-10-02');
assert.equal(bench.peak.value,70*(1+5/30));assert.equal(bench.peak.date,'2026-10-02');
console.log('PASS: daily means, normalized aggregate, incomplete/zero sets, Epley limits, 30-day heatmap and muscle mapping.');
